import 'package:flutter/foundation.dart';
import 'package:shared_preferences/shared_preferences.dart';

enum AppLang { en, si, ta }

/// Central translations for irrigation, fertilizer, weather, history, and reports.
/// Screens call [t] instead of hard-coding English labels.
class LanguageController extends ChangeNotifier {
  LanguageController._();
  static final LanguageController instance = LanguageController._();

  static const _prefKey = 'app_language';

  AppLang lang = AppLang.en;

  Future<void> load() async {
    final prefs = await SharedPreferences.getInstance();
    final raw = prefs.getString(_prefKey);
    lang = switch (raw) {
      'si' => AppLang.si,
      'ta' => AppLang.ta,
      _ => AppLang.en,
    };
    notifyListeners();
  }

  Future<void> setLang(AppLang value) async {
    lang = value;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_prefKey, value.name);
    notifyListeners();
  }

  String t(String key) {
    return _tables[lang]?[key] ?? _en[key] ?? key;
  }

  String tf(String key, Map<String, String> vars) {
    var value = t(key);
    vars.forEach((name, replacement) {
      value = value.replaceAll('{$name}', replacement);
    });
    return value;
  }

  static const _tables = {
    AppLang.en: _en,
    AppLang.si: _si,
    AppLang.ta: _ta,
  };
}

String t(String key) => LanguageController.instance.t(key);

String tf(String key, Map<String, String> vars) =>
    LanguageController.instance.tf(key, vars);

String irrigationDecisionLabel(String? code, [String? fallback]) {
  switch (code) {
    case 'SKIP_RAIN_EXPECTED':
      return t('waitForRain');
    case 'SKIP_SOIL_ALREADY_WET':
      return t('soilAlreadyWet');
    case 'SUITABLE_TO_IRRIGATE':
    case 'SUITABLE_BASED_ON_SOIL':
      return t('irrigateNow');
    case 'NO_URGENT_IRRIGATION':
      return t('noUrgent');
    default:
      return fallback ?? t('irrigationRecommendation');
  }
}


String growthStageShortLabel(String? stage) {
  switch (stage) {
    case 'Bud':
      return t('growthBud');
    case 'Flower':
      return t('growthFlower');
    case 'EarlyFruit':
      return t('growthEarlyFruit');
    case 'MidGrowth':
      return t('growthMidGrowth');
    case 'MatureFruit':
      return t('growthMature');
    case 'Ready to Harvest':
      return t('readyToHarvest');
    default:
      return stage == null || stage.isEmpty ? t('unknown') : stage;
  }
}

String growthStageLabel(String? stage) {
  switch (stage) {
    case 'Bud':
      return t('growthBudStage');
    case 'Flower':
      return t('growthFlowerStage');
    case 'EarlyFruit':
      return t('growthEarlyFruitStage');
    case 'MidGrowth':
      return t('growthMidGrowthStage');
    case 'MatureFruit':
      return t('growthMatureStage');
    case 'Ready to Harvest':
      return t('readyToHarvest');
    default:
      return stage == null || stage.isEmpty ? t('unknown') : stage;
  }
}

String growthConditionLabel(String? value) {
  final normalized = (value ?? '').trim().toLowerCase();
  switch (normalized) {
    case 'favourable':
    case 'favorable':
      return t('favourable');
    case 'caution':
      return t('caution');
    case 'clear':
      return t('clear');
    case 'cloudy':
      return t('cloudy');
    case 'partly cloudy':
      return t('partlyCloudy');
    case 'rain':
    case 'rainy':
      return t('rain');
    case 'unavailable':
      return t('unavailable');
    case 'unknown':
      return t('unknown');
    case 'soil sensor data unavailable':
      return t('soilSensorUnavailable');
    default:
      return value == null || value.isEmpty ? t('unknown') : value;
  }
}

